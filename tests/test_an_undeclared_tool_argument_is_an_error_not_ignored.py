"""A tool argument the tool never declared was accepted and ignored.

Measured on 2026-10-09: GLM-5.3-Flash called ``read_file`` with ``offset`` where the schema declares
``start_line``. ``Tool.run(**kwargs)`` takes anything, ``ToolRegistry.run`` passed everything
through, and ``read_file`` reads only the keys it knows — so every call returned the SAME first
window. To the model that was a successful read that did not move; it asked four more times, the
loop guard warned, and the turn hung. Nothing raised anywhere.

The fix: a name absent from the tool's declared schema is an error observation that names it and
lists what the tool accepts, so the next call can be the right one. No alias: ``offset`` silently
becoming ``start_line`` would hide the mistake from the model and from us.

Where it does NOT apply, on purpose:

- a schema that declares ``additionalProperties`` (``true`` or a schema), or declares no
  ``properties`` at all — free-form by its own words; and an EMPTY ``properties``, which is the base
  class's default and so means "declared nothing" (only ``additionalProperties: false`` says
  "takes nothing");
- an MCP tool, whose arguments go verbatim to a server that validates them against its own schema,
  where an absent ``additionalProperties`` means *allowed* (JSON Schema's default) — unless that
  schema says ``additionalProperties: false``.

An OpenAPI connector IS checked: its schema is generated by us, and its ``run`` keeps only the path,
query and body names, so an unknown argument was dropped here exactly as ``offset`` was.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from chimera.core.agent import Agent, AgentConfig, ToolActivity
from chimera.core.tool_loop import ToolLoopDetector
from chimera.governance.ledger import TaintLedger
from chimera.governance.ledger_tool import LedgeredTool
from chimera.integrations.mcp_client import MCPTool, MCPToolSpec
from chimera.providers.gateway import CompletionResult, ToolCall
from chimera.skills.aliases import adapt_registry
from chimera.tools.base import Tool, undeclared_arguments
from chimera.tools.defer import defer_builtins
from chimera.tools.files import ReadFileTool
from chimera.tools.registry import ToolRegistry

_TEXT = "one\ntwo\nthree\n"


def _read_file(tmp_path: Path) -> ReadFileTool:
    (tmp_path / "f.txt").write_text(_TEXT, encoding="utf-8")
    return ReadFileTool(tmp_path)


def _registry(*tools: Tool) -> ToolRegistry:
    registry = ToolRegistry()
    for tool in tools:
        registry.register(tool)
    return registry


class _Counting(Tool):
    """Declares one argument and counts how often it actually ran."""

    name = "probe"
    description = "probe"
    parameters = {"type": "object", "properties": {"x": {"type": "string"}}, "required": ["x"]}

    def __init__(self) -> None:
        self.calls = 0

    def run(self, **kwargs: Any) -> str:
        self.calls += 1
        return f"ran with {sorted(kwargs)}"


class _FreeForm(Tool):
    """Says, in its schema, that it takes names it did not list."""

    name = "free"
    description = "free-form"
    parameters = {
        "type": "object",
        "properties": {"known": {"type": "string"}},
        "additionalProperties": True,
    }

    def run(self, **kwargs: Any) -> str:
        return f"got {sorted(kwargs)}"


# --- the incident ---------------------------------------------------------------------------------


def test_read_file_with_offset_is_an_error_that_names_it_and_lists_the_accepted(
    tmp_path: Path,
) -> None:
    out = _registry(_read_file(tmp_path)).run("read_file", path="f.txt", offset=2)

    assert out.startswith("error:"), f"the unknown argument was ignored: {out!r}"
    assert "'offset'" in out
    assert "path, start_line, max_lines" in out
    assert "one" not in out, "the tool ran anyway and returned its first window"


def test_read_file_with_its_declared_arguments_still_reads(tmp_path: Path) -> None:
    out = _registry(_read_file(tmp_path)).run("read_file", path="f.txt", start_line=2, max_lines=1)

    assert out.startswith("two"), out


def test_the_tool_does_not_run_when_an_argument_is_unknown() -> None:
    probe = _Counting()
    out = _registry(probe).run("probe", x="a", y="b", z="c")

    assert probe.calls == 0
    assert out == "error: probe: unknown arguments 'y', 'z'; accepted: x"


def test_through_the_wrappers_the_inner_schema_is_what_is_checked(tmp_path: Path) -> None:
    out = _registry(LedgeredTool(_read_file(tmp_path), TaintLedger())).run(
        "read_file", path="f.txt", offset=2
    )

    assert "unknown argument 'offset'" in out


# --- what stays open ------------------------------------------------------------------------------


def test_a_schema_that_declares_additional_properties_keeps_its_extras() -> None:
    assert _registry(_FreeForm()).run("free", known="a", other="b") == "got ['known', 'other']"


def test_a_schema_with_no_properties_list_is_free_form() -> None:
    class _Bare(Tool):
        name = "bare"
        description = "bare"
        parameters = {"type": "object"}

        def run(self, **kwargs: Any) -> str:
            return f"got {sorted(kwargs)}"

    assert _registry(_Bare()).run("bare", anything=1) == "got ['anything']"


def test_the_base_classes_empty_default_declares_nothing_rather_than_no_arguments() -> None:
    """``{"properties": {}}`` is what a Tool that never set ``parameters`` has. Reading it as "takes
    no arguments" would break every such tool on its first argument; ``false`` says that instead."""

    class _Undeclared(Tool):
        name = "undeclared"
        description = "d"

        def run(self, **kwargs: Any) -> str:
            return f"got {sorted(kwargs)}"

    class _NoArgs(_Undeclared):
        name = "noargs"
        parameters = {"type": "object", "properties": {}, "additionalProperties": False}

    registry = _registry(_Undeclared(), _NoArgs())
    assert registry.run("undeclared", a=1) == "got ['a']"
    assert registry.run("noargs", a=1) == "error: noargs: unknown argument 'a'; accepted: none"


def _mcp(schema: dict[str, Any], seen: list[dict[str, Any]]) -> MCPTool:
    def caller(name: str, arguments: dict[str, Any]) -> str:
        seen.append(arguments)
        return "ok"

    return MCPTool(MCPToolSpec(name="remote", description="d", input_schema=schema), caller)


def test_an_mcp_tool_forwards_an_undeclared_argument_to_its_server() -> None:
    seen: list[dict[str, Any]] = []
    schema = {"type": "object", "properties": {"q": {"type": "string"}}}
    out = _registry(_mcp(schema, seen)).run("remote", q="a", extra=1)

    assert not out.startswith("error:"), out
    assert seen == [{"q": "a", "extra": 1}]


def test_an_mcp_tool_whose_schema_is_closed_is_checked() -> None:
    seen: list[dict[str, Any]] = []
    schema = {
        "type": "object",
        "properties": {"q": {"type": "string"}},
        "additionalProperties": False,
    }
    out = _registry(_mcp(schema, seen)).run("remote", q="a", extra=1)

    assert out == "error: remote: unknown argument 'extra'; accepted: q"
    assert seen == []


def test_the_search_files_alias_still_takes_its_own_file_glob(tmp_path: Path) -> None:
    """The alias translates ``file_glob`` to grep's ``glob``. Its schema was grep's, so the new check
    would have refused the one argument the alias exists to translate."""
    from chimera.tools.builtin import default_registry

    (tmp_path / "a.py").write_text("needle\n", encoding="utf-8")
    registry = adapt_registry(default_registry(tmp_path))
    out = registry.run("search_files", pattern="needle", file_glob="*.py")

    assert not out.startswith("error:"), out
    assert "needle" in out


def test_a_deferred_tool_call_is_checked_too() -> None:
    """``tool_call`` runs the deferred tool itself, not through the registry."""
    class _Scrape(_Counting):
        # Only a name the product ships is deferred (`defer.SHIPPED_BUILTINS`), so the probe borrows one.
        name = "scrape"

    probe = _Scrape()
    deferred, count = defer_builtins(_registry(probe))
    assert count == 1, "precondition: the probe sits behind tool_call"
    out = deferred.run("tool_call", tool="scrape", arguments={"x": "a", "offset": 2})

    assert out == "error: scrape: unknown argument 'offset'; accepted: x"
    assert probe.calls == 0


def test_undeclared_arguments_lists_names_in_call_order() -> None:
    assert undeclared_arguments(_Counting(), {"b": 1, "x": 2, "a": 3}) == ["b", "a"]
    assert undeclared_arguments(_FreeForm(), {"b": 1}) == []


# --- inside the loop ------------------------------------------------------------------------------


class _Backend:
    """Calls ``probe`` with the scripted argument sets, then answers."""

    def __init__(self, calls: list[dict[str, Any]]) -> None:
        self.calls = list(calls)

    def complete(self, messages: Any, *, tools: Any = None, **kwargs: Any) -> CompletionResult:
        if self.calls and tools is not None:
            call = ToolCall(id=f"c{len(self.calls)}", name="probe", arguments=self.calls.pop(0))
            return CompletionResult(content="", model="fake", tool_calls=[call])
        return CompletionResult(content="final", model="fake")


def test_in_the_loop_it_is_an_observation_and_the_turn_goes_on() -> None:
    probe = _Counting()
    seen: list[ToolActivity] = []
    agent = Agent(_Backend([{"x": "a", "offset": 2}, {"x": "a"}]), _registry(probe), AgentConfig(max_steps=6))
    result = agent.run("go", on_tool=seen.append)

    assert result.answer == "final"
    assert [a.ok for a in seen] == [False, True]
    assert "unknown argument 'offset'; accepted: x" in seen[0].observation
    assert probe.calls == 1, "only the corrected call ran"


def test_the_same_unknown_argument_repeated_stops_the_run() -> None:
    """The loop guard sees the identical failing call. It was what fired on 2026-10-09; with the
    error in place of a silent success it now hears a failure, and stops a model that ignores it."""
    probe = _Counting()
    agent = Agent(_Backend([{"x": "a", "offset": 2}] * 8), _registry(probe), AgentConfig(max_steps=12))
    result = agent.run("go")

    assert result.stopped_reason == "tool_loop"
    assert probe.calls == 0


def test_the_detector_breaks_on_an_identical_failing_call() -> None:
    detector = ToolLoopDetector()
    error = "error: probe: unknown argument 'offset'; accepted: x"
    verdicts = [detector.record("probe", {"offset": 2}, error, ok=False) for _ in range(5)]

    assert verdicts[2].level == "warn"
    assert verdicts[-1].tripped
