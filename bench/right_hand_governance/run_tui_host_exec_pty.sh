#!/usr/bin/env bash
# Part 2: is the host-exec confirmation prompt answerable inside `chimera tui`?
#
# The governance study INFERRED that it is not -- Textual owns the terminal, the prompt is a
# `typer.confirm` on raw stdin run on a worker thread, `_human_can_answer()` still returns True
# because stdin really is a tty, and PROMPT_TIMEOUT_SECONDS then refuses after two minutes. Nothing
# in the repository had run it. This runs it.
#
#   MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' wsl bash bench/right_hand_governance/run_tui_host_exec_pty.sh
#
# `ARMS=tui` (or `ARMS=chat`) re-runs one arm without paying for the other; `TAG=` names the
# transcripts. An existing transcript is never overwritten -- pass `FORCE=1` to mean it.
#
# Do NOT edit this file while it is running. `bash` resumes reading a script at a byte offset, so an
# edit that changes the file's length can make it re-execute a line it has already run. That is how
# the `chat` arm of 2026-09-08 ran twice and overwrote its own first transcript.
#
# Both arms use the SAME prompt, the SAME model and the SAME settings, and differ only in the
# command. `chat` is the control: there the prompt is expected to work, so if it does not appear
# there either, the finding is about the harness and not about Textual.
#
# `id -un` is the command on purpose. It changes nothing; `chimera/tools/readonly.py` does not list
# `id`, so it reaches the gate instead of being waved through by `_skip_what_only_reads`; and its
# OUTPUT (the username) does not appear anywhere in the text typed at the app, so seeing it on
# screen means the command really ran rather than that the prompt echoed.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/results"
mkdir -p "$OUT"

CHIMERA=/home/brcamp/hb-venv/bin/chimera
PY=/home/brcamp/hb-venv/bin/python
MODEL="openrouter/deepseek/deepseek-chat-v3.1"
# Deliberately does NOT contain the string `run_shell`. The first pass did, and the tool name then
# had its "first appearance" recorded at t+8s -- the echo of the typed prompt, not the tool call.
# A needle that the harness itself types is not an observation
# (results/2026-09-08-tui-first-pass-contaminated-needle.txt keeps that pass).
ASK="Execute this on the machine with your shell tool and tell me the exact output: id -un"

eval "$(tr -d '\r' < "/mnt/c/Users/brcam/Desktop/Desenvolvendo Projetos/Agent AI/.env" | grep -E '^[A-Za-z_]+=' | sed 's/^/export /')"
if [ -z "${OPENROUTER_API_KEY:-}" ]; then echo "no key; aborting"; exit 1; fi

export CHIMERA_SANDBOX=local
unset CHIMERA_HOST_EXEC || true      # leave it at its default, `ask` -- that is the subject
export TERM=xterm-256color
export PYTHONUNBUFFERED=1

# ARMS=tui or ARMS=chat re-runs one arm without paying for the other. Default: both.
ARMS="${ARMS:-tui chat}"

TAG="${TAG:-2026-09-08}"

run_arm() {
  label="$1"; cmd="$2"; timeout="$3"; shift 3
  case " $ARMS " in *" $label "*) ;; *) echo "=== arm $label skipped (ARMS=$ARMS) ==="; return 0;; esac
  out="$OUT/$TAG-$label.txt"
  if [ -e "$out" ] && [ -z "${FORCE:-}" ]; then
    echo "=== arm $label skipped: $out exists (TAG= to name it, FORCE=1 to overwrite) ==="
    return 0
  fi
  home="$(mktemp -d)"
  echo "=== arm $label (fresh CHIMERA_HOME) ==="
  CHIMERA_HOME="$home" "$PY" "$HERE/pty_drive.py" \
    --label "$label" \
    --cmd "stty rows 40 cols 120 2>/dev/null; $cmd" \
    --send "$ASK" --send-after 8 --timeout "$timeout" \
    --watch "thinking" \
    --watch "run_shell" \
    --watch "Run it?" \
    --watch "wants to run this on your machine" \
    --watch "declined" \
    --watch "$(id -un)" \
    --out "$out" "$@"
  rm -rf "$home"
  echo
}

# --- arm 1: the TUI ------------------------------------------------------------------------
# 300s: the inferred failure is a 120s block INSIDE the turn, so the ceiling has to clear the
# model latency plus the timeout plus the redraw, or a hang would be indistinguishable from an
# impatient harness.
run_arm tui "$CHIMERA tui --model $MODEL --no-memory --no-stream" 300

# --- arm 2: chat, the control --------------------------------------------------------------
# Answers `y` when the prompt appears. Answering proves two things at once: the question reached
# the screen, and the answer reached the tool -- the username in the reply is the second half.
run_arm chat "$CHIMERA chat --model $MODEL --no-memory --new" 180 --reply "Run it?::y"

echo "transcripts in $OUT"
