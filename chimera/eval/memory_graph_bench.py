"""Does the graph memory layer earn its place? — the measurement it never had.

``chimera/memory/graph.py`` landed on 2026-06-30 and feeds real recall: ``_recall_graph`` in the
CLI and in the desktop manager build a :class:`~chimera.memory.graph.MemoryGraph` from stored
memories, and :func:`chimera.interface.session.recall_facts` appends its entity-linked facts to
every turn's prompt. Nothing ever measured whether that helps. ``memory_bench.py`` does not mention
the graph; ``tests/test_memory_graph.py`` proves the extractor extracts, which is correctness of the
module and says nothing about usefulness of the feature.

**The design constraint that shapes everything below.** ``MemoryGraph.related_facts`` iterates
``sorted(self.entities())`` and returns ``facts[:k]``. There is no ranking: the ``k`` triples that
reach the prompt are the alphabetically first ones. And it does not traverse — only entities named
*in the query* contribute their relations, so a fact one hop away from the query is unreachable by
construction. Both are measured here rather than asserted, and the second is registered as a
prediction that the ``traverse`` slice will stay at zero.

Three arms over the identical corpus, identical queries, identical fact budget where it matters:

``baseline``  keyword recall, ``k=3`` — the production default with ``graph=None``
``graph``     the same, plus the graph — the shipped wiring
``budget``    keyword recall at ``k=6``, no graph — the control that asks the honest question,
              because ``graph`` returns up to ``k`` facts *on top of* the ``k`` lexical ones. A
              layer that only widens the prompt is not an entity-aware retriever, and without this
              arm any lift it shows is unattributable.

Three slices, generated by the SAME machinery from the same pools so nothing superficial separates
them (a slice built by its own code path carries the signature of that path, not of the property
under test):

``multihop``  the answer needs TWO stored facts about the entity named in the query — more than the
              baseline's budget can hold. Where the graph *should* win.
``single``    the answer needs ONE fact, and the query pins it lexically. The control: the graph has
              nothing to add here, so whatever it does add is cost.
``traverse``  the answer needs a fact about an entity reachable only through one hop. The mechanism
              ceiling, registered as a predicted null.

Everything is deterministic and offline: no model, no network. What is measured is **retrieval** —
whether the facts an answer needs reach the prompt. Whether a model then uses them is the open half,
the same honesty ``memory_poison.py`` keeps about susceptibility.

Design, thresholds and predictions are fixed in ``bench/memory_graph/PREREGISTRATION.md``.
"""

