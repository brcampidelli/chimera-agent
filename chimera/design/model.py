"""The Chimera Design document: what a visual artefact is, and the invariants every copy of it keeps.

A document is pages of artboards; an artboard lists its top-level elements in paint order, and a group
lists its children the same way. Every element lives in ``nodes`` exactly once and is referenced from
exactly one place, an artboard or a group, which is what :meth:`DesignDocument._check_integrity`
enforces. Frames are in artboard coordinates even inside a group.

**The wire format is camelCase**, identical to the desktop's TypeScript model
(``apps/desktop/src/lib/design/model.ts``). Fields are snake_case in Python and serialise through a
camelCase alias; :func:`wire` (aliases on, ``None`` left out) is how every document and operation
leaves this package. An optional field that is ``None`` is *absent* on the wire, which is what lets a
``node.update`` patch remove one with ``null``.

**Why every model forbids unknown keys and runs strict.** The second writer of these documents is a
language model. A field this schema does not know is either a typo that would be silently dropped or
an attempt to smuggle something the renderer might read later; refusing both is cheaper than deciding
which. Strict mode stops ``"12"`` from becoming ``12`` for the same reason: a proposal either is the
shape it claims to be, or it is reported.

**Why there is no owner field.** The handoff's TypeScript reference carries ``ownerId``. Chimera is a
single-owner app: the documents live in that owner's home directory and every route is already behind
the owner's own credential, so an owner id would be a value nobody checks — a field that suggests a
multi-user access control which does not exist. If Chimera ever serves several people, ownership
belongs in the store's path and the route's auth, not in a field the document carries about itself.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Annotated, Any, Final, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator
from pydantic.alias_generators import to_camel

#: The version this build writes. ``migrate.py`` brings older documents up to it.
SCHEMA_VERSION: Final = 1

# ---- limits -----------------------------------------------------------------------------------
#: Generous for a person, small enough that a runaway model reply cannot make a document that hurts
#: to load, render or send back to the model. Where the desktop has the same limit, they agree.
MAX_TITLE = 160
MAX_NODE_NAME = 120
MAX_TEXT = 20_000
MAX_ALT = 1_000
MAX_COMMENT = 2_000
MAX_AUTHOR = 200
MIN_DIMENSION = 1
MAX_DIMENSION = 20_000
#: Positions may leave the artboard (an element half off the edge is legitimate), but not by an
#: absurd amount: this bounds what an exporter has to format.
MAX_COORDINATE = 1_000_000
#: The desktop's ``LIMITS.operations``. Model proposals have their own, lower cap (``propose.py``).
MAX_OPS_PER_CALL = 500
MAX_NODES = 5_000
MAX_PAGES = 50
MAX_ARTBOARDS_PER_PAGE = 50
MAX_COMMENTS = 1_000
MAX_GROUP_DEPTH = 32
MAX_TOKENS_PER_GROUP = 200
#: The desktop's ``SAFE_ID`` length.
MAX_ID = 100
#: A path's vertices (the desktop's ``LIMITS.pathPoints``); stored as twice as many numbers.
MAX_PATH_POINTS = 4_000

#: Identifiers are path- and HTML-safe by construction. Generated by the server for anything new a
#: model proposes (see ``ids.remap_new_ids``); this pattern is the second line, for ids in a payload.
ID_PATTERN = rf"^[A-Za-z0-9_-]{{1,{MAX_ID}}}$"
#: ``#RRGGBB`` or ``#RRGGBBAA`` and nothing else: no names, no ``rgb()``, no ``url()`` — the value is
#: written into an SVG attribute and a CSS declaration later, and a closed pattern is what makes that
#: safe without a CSS parser.
COLOR_PATTERN = r"^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$"
#: Token names are keys and references only, never written into markup, so spaces are allowed.
TOKEN_NAME_PATTERN = r"^[A-Za-z0-9][A-Za-z0-9 ._-]{0,99}$"
#: A font family list as CSS writes it, without the characters that would end a declaration or an
#: attribute (``;``, ``{``, ``}``, ``<``, ``>``, ``"``, ``\\``).
FONT_FAMILY_PATTERN = r"^[A-Za-z0-9 ,'._-]{1,200}$"

SafeId = Annotated[str, StringConstraints(pattern=ID_PATTERN)]
Color = Annotated[str, StringConstraints(pattern=COLOR_PATTERN)]
TokenName = Annotated[str, StringConstraints(pattern=TOKEN_NAME_PATTERN)]
Coordinate = Annotated[float, Field(ge=-MAX_COORDINATE, le=MAX_COORDINATE)]
Dimension = Annotated[float, Field(ge=MIN_DIMENSION, le=MAX_DIMENSION)]
Name = Annotated[str, StringConstraints(max_length=MAX_NODE_NAME)]
Unit = Annotated[float, Field(ge=0, le=1)]


class DesignError(ValueError):
    """Anything the design domain refuses. A ``ValueError`` so generic handlers already catch it."""


class _Strict(BaseModel):
    model_config = ConfigDict(
        extra="forbid",
        strict=True,
        allow_inf_nan=False,
        alias_generator=to_camel,
        validate_by_alias=True,
        validate_by_name=True,
        serialize_by_alias=True,
    )


def wire(model: BaseModel) -> dict[str, Any]:
    """The JSON a model travels as: camelCase keys, optional fields that are ``None`` left out."""
    return model.model_dump(mode="json", by_alias=True, exclude_none=True)


class Rect(_Strict):
    """A frame in artboard coordinates. Rotation is in degrees, about the frame's centre."""

    x: Coordinate
    y: Coordinate
    width: Dimension
    height: Dimension
    rotation: Annotated[float, Field(ge=-360, le=360)] | None = None


class Style(_Strict):
    fill: Color | None = None
    stroke: Color | None = None
    stroke_width: Annotated[float, Field(ge=0, le=1_000)] | None = None
    opacity: Unit | None = None
    radius: Annotated[float, Field(ge=0, le=MAX_DIMENSION)] | None = None


class _NodeBase(_Strict):
    """Common element fields.

    ``parent_id`` mirrors the desktop's optional ``parentId``. It is derived data, so when present it
    must name the group that actually contains the element (checked in :func:`check_integrity`) —
    never a second source of truth that can disagree with the tree.
    """

    id: SafeId
    name: Name = ""
    frame: Rect
    parent_id: SafeId | None = None
    locked: bool = False
    visible: bool = True
    style: Style = Field(default_factory=Style)


class TextNode(_NodeBase):
    type: Literal["text"]
    text: Annotated[str, StringConstraints(max_length=MAX_TEXT)]
    font_token: TokenName | None = None
    color_token: TokenName | None = None
    align: Literal["left", "center", "right"] | None = None


class ShapeNode(_NodeBase):
    """A shape. ``points`` is ``[x0, y0, x1, y1, ...]`` normalised to the frame.

    0 is the frame's left/top edge and 1 its right/bottom, so resizing the frame scales the drawing:
    a ``path``'s vertices, or a ``line``'s two ends (which keep its direction; without them a line
    runs from the top-left corner to the bottom-right). Any shape may carry them.
    """

    type: Literal["shape"]
    shape: Literal["rectangle", "ellipse", "line", "path"]
    points: Annotated[list[Unit], Field(max_length=MAX_PATH_POINTS * 2)] | None = None

    @model_validator(mode="after")
    def _points_pair_up(self) -> ShapeNode:
        if self.points is not None:
            if len(self.points) % 2:
                raise ValueError("points are x, y pairs: the count must be even")
            if self.shape == "line" and len(self.points) != 4:
                raise ValueError("a line's points are exactly its two ends")
        return self


class ImageNode(_NodeBase):
    """An image by local asset id — never a URL. ``assets.py`` is what admits the bytes."""

    type: Literal["image"]
    asset_id: SafeId
    alt: Annotated[str, StringConstraints(max_length=MAX_ALT)] = ""
    fit: Literal["contain", "cover"] = "contain"


class GroupNode(_NodeBase):
    type: Literal["group"]
    child_ids: Annotated[list[SafeId], Field(max_length=MAX_NODES)] = Field(default_factory=list)


DesignNode = Annotated[TextNode | ShapeNode | ImageNode | GroupNode, Field(discriminator="type")]

#: The keys (wire names) an update may change, per element type — the desktop's ``PATCH_KEYS``.
#: ``id`` and ``type`` are never among them. A group's ``childIds`` is, as on the desktop, but the
#: whole-document check after every batch still requires each element placed exactly once, so a
#: patch can reorder a group's children and can never claim somebody else's element.
_COMMON_PATCH = ("name", "frame", "parentId", "locked", "visible", "style")
PATCHABLE: dict[str, tuple[str, ...]] = {
    "text": (*_COMMON_PATCH, "text", "fontToken", "colorToken", "align"),
    "shape": (*_COMMON_PATCH, "shape", "points"),
    "image": (*_COMMON_PATCH, "assetId", "alt", "fit"),
    "group": (*_COMMON_PATCH, "childIds"),
}
#: Fields a patch may change but never remove with ``null`` (the desktop's ``REQUIRED``).
REQUIRED_FIELDS = frozenset(
    {"name", "frame", "visible", "text", "shape", "assetId", "alt", "fit", "childIds"}
)


class Artboard(_Strict):
    id: SafeId
    name: Name = ""
    width: Dimension
    height: Dimension
    background: Color = "#FFFFFF"
    node_ids: Annotated[list[SafeId], Field(max_length=MAX_NODES)] = Field(default_factory=list)


ARTBOARD_PATCHABLE = ("name", "width", "height", "background")


class Page(_Strict):
    id: SafeId
    name: Name = ""
    artboards: Annotated[list[Artboard], Field(max_length=MAX_ARTBOARDS_PER_PAGE)] = Field(
        default_factory=list
    )


def utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


class Comment(_Strict):
    """A note pinned to a point of an artboard, optionally about one element.

    A comment may outlive what it points at: deleting the element or the artboard leaves its id
    dangling, so undoing the delete re-attaches the conversation instead of losing it. Undo works in
    either order because adding a comment never requires its targets to exist; screens show such a
    comment as attached to something removed.
    """

    id: SafeId
    artboard_id: SafeId
    node_id: SafeId | None = None
    x: Coordinate
    y: Coordinate
    text: Annotated[str, StringConstraints(min_length=1, max_length=MAX_COMMENT)]
    author: Annotated[str, StringConstraints(max_length=MAX_AUTHOR)] = ""
    resolved: bool = False
    created_at: Annotated[str, StringConstraints(max_length=40)] = Field(default_factory=utc_now)

    @model_validator(mode="after")
    def _not_blank(self) -> Comment:
        if not self.text.strip():
            raise ValueError("a comment cannot be blank")
        return self


class TypographyToken(_Strict):
    family: Annotated[str, StringConstraints(pattern=FONT_FAMILY_PATTERN)]
    size: Annotated[float, Field(ge=1, le=512)]
    weight: Annotated[int, Field(ge=100, le=900)]
    line_height: Annotated[float, Field(ge=0.5, le=4)] | None = None


#: Which token group a component role names. A role not listed may name a token of any group.
COMPONENT_ROLE_GROUPS: dict[str, str] = {
    "fill": "colors",
    "text": "colors",
    "stroke": "colors",
    "background": "colors",
    "font": "typography",
    "radius": "radii",
    "padding": "spacing",
    "gap": "spacing",
}


class DesignTokens(_Strict):
    """A design system as data: named colours, type styles, spacings, radii and component recipes.

    ``components`` is the semantic layer: ``{"button.primary": {"fill": "primary", "font": "label"}}``
    says what a primary button is made of, by token name, so a checker can tell "uses the system"
    from "happens to use the same hex". The desktop's tokens have no ``components`` yet; it defaults
    to empty, so their payloads validate unchanged.
    """

    colors: Annotated[dict[TokenName, Color], Field(max_length=MAX_TOKENS_PER_GROUP)] = Field(
        default_factory=dict
    )
    typography: Annotated[
        dict[TokenName, TypographyToken], Field(max_length=MAX_TOKENS_PER_GROUP)
    ] = Field(default_factory=dict)
    spacing: Annotated[
        dict[TokenName, Annotated[float, Field(ge=0, le=MAX_DIMENSION)]],
        Field(max_length=MAX_TOKENS_PER_GROUP),
    ] = Field(default_factory=dict)
    radii: Annotated[
        dict[TokenName, Annotated[float, Field(ge=0, le=MAX_DIMENSION)]],
        Field(max_length=MAX_TOKENS_PER_GROUP),
    ] = Field(default_factory=dict)
    components: Annotated[
        dict[TokenName, Annotated[dict[TokenName, TokenName], Field(max_length=20)]],
        Field(max_length=MAX_TOKENS_PER_GROUP),
    ] = Field(default_factory=dict)

    @model_validator(mode="after")
    def _components_name_real_tokens(self) -> DesignTokens:
        groups: dict[str, set[str]] = {
            "colors": set(self.colors),
            "typography": set(self.typography),
            "spacing": set(self.spacing),
            "radii": set(self.radii),
        }
        every = set().union(*groups.values())
        for component, roles in self.components.items():
            for role, token in roles.items():
                group = COMPONENT_ROLE_GROUPS.get(role)
                known = groups[group] if group else every
                if token not in known:
                    where = f"the {group} tokens" if group else "the tokens"
                    raise ValueError(
                        f"component {component!r} role {role!r} names {token!r}, not in {where}"
                    )
        return self


class DesignDocument(_Strict):
    schema_version: Literal[1] = SCHEMA_VERSION
    id: SafeId
    title: Annotated[str, StringConstraints(min_length=1, max_length=MAX_TITLE)]
    revision: Annotated[int, Field(ge=0)] = 0
    updated_at: Annotated[str, StringConstraints(max_length=40)] = Field(default_factory=utc_now)
    design_system_id: SafeId | None = None
    tokens: DesignTokens = Field(default_factory=DesignTokens)
    pages: Annotated[list[Page], Field(max_length=MAX_PAGES)] = Field(default_factory=list)
    nodes: Annotated[dict[SafeId, DesignNode], Field(max_length=MAX_NODES)] = Field(
        default_factory=dict
    )
    comments: Annotated[list[Comment], Field(max_length=MAX_COMMENTS)] = Field(
        default_factory=list
    )

    @model_validator(mode="after")
    def _check_integrity(self) -> DesignDocument:
        check_integrity(self)
        return self

    def to_json(self) -> dict[str, Any]:
        return wire(self)


def check_integrity(doc: DesignDocument) -> None:
    """Raise ``ValueError`` unless the tree is a forest rooted at the artboards.

    Every element is referenced exactly once, every reference resolves, nothing is unreachable (which
    is also how a cycle shows up: a ring of groups that no artboard reaches), nesting is bounded, and
    a ``parentId`` that is present tells the truth.
    """
    if not doc.title.strip():
        raise ValueError("the title cannot be blank")
    for key, node in doc.nodes.items():
        if key != node.id:
            raise ValueError(f"element stored under {key!r} has id {node.id!r}")
    _unique((p.id for p in doc.pages), "page")
    _unique((a.id for p in doc.pages for a in p.artboards), "artboard")
    _unique((c.id for c in doc.comments), "comment")

    seen: set[str] = set()

    def claim(node_id: str, owner: str) -> None:
        if node_id not in doc.nodes:
            raise ValueError(f"{owner} references missing element {node_id!r}")
        if node_id in seen:
            raise ValueError(f"element {node_id!r} is referenced more than once")
        seen.add(node_id)

    parents: dict[str, str] = {}
    for node in doc.nodes.values():
        if isinstance(node, GroupNode):
            for child in node.child_ids:
                if child == node.id:
                    raise ValueError(f"group {node.id!r} contains itself")
                claim(child, f"group {node.id!r}")
                parents[child] = node.id
    for page in doc.pages:
        for artboard in page.artboards:
            for node_id in artboard.node_ids:
                claim(node_id, f"artboard {artboard.id!r}")
    if len(seen) != len(doc.nodes):
        orphans = sorted(set(doc.nodes) - seen)[:5]
        raise ValueError(f"elements not placed on any artboard: {orphans}")
    for node in doc.nodes.values():
        if node.parent_id is not None and parents.get(node.id) != node.parent_id:
            raise ValueError(f"element {node.id!r} names {node.parent_id!r} as its parent, wrongly")

    reached = 0
    stack = [(nid, 1) for p in doc.pages for a in p.artboards for nid in a.node_ids]
    while stack:
        node_id, depth = stack.pop()
        if depth > MAX_GROUP_DEPTH:
            raise ValueError(f"groups nest deeper than {MAX_GROUP_DEPTH}")
        reached += 1
        node = doc.nodes[node_id]
        if isinstance(node, GroupNode):
            stack.extend((child, depth + 1) for child in node.child_ids)
    if reached != len(doc.nodes):
        raise ValueError("groups form a cycle that no artboard reaches")


def _unique(ids: Any, kind: str) -> None:
    found: set[str] = set()
    for value in ids:
        if value in found:
            raise ValueError(f"duplicate {kind} id {value!r}")
        found.add(value)
