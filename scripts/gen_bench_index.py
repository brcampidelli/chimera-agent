"""Generate bench/INDEX.md: one line per directory of bench/, with a status read from its files.

    python scripts/gen_bench_index.py           # rewrite bench/INDEX.md
    python scripts/gen_bench_index.py --check   # exit 1 if the file on disk is stale

Why it exists: bench/ holds well over a hundred directories and nothing said which ones carry a
pre-registration, which carry a result, and which carry neither. The answer is a fact about files,
so it is derived from files and never written by hand.

The status is NOT a conclusion. It says what documents exist, not what they found. Read the
directory's RESULTS file for that.

Status, from the tracked files under bench/<dir>/ (any depth):

- ``with result``: at least one file whose name starts with ``RESULT``.
- ``preregistered, no result``: a ``PREREGISTRATION*`` file and no ``RESULT*`` file.
- ``wrapper``: neither of the two, and every file is a script (.py/.sh) or a README. A thin driver
  or a companion sweep whose claims live in another directory.
- ``neither``: neither of the two, and something other than scripts and a README.

Names are matched in upper case on purpose: ``results.json`` is data, ``RESULTS.md`` is the report.
The listing is ``git ls-files`` (tracked plus untracked-and-not-ignored), so a new directory is
indexed before its first commit and a gitignored scratch directory cannot change the index.
"""

from __future__ import annotations

import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "bench"
INDEX = BENCH / "INDEX.md"

WITH_RESULT = "with result"
PREREG_ONLY = "preregistered, no result"
WRAPPER = "wrapper"
NEITHER = "neither"

_SCRIPT_SUFFIXES = (".py", ".sh")

HEADER = """\
# bench/ index

Generated by `scripts/gen_bench_index.py`; do not edit by hand. A test fails when this file is
stale or a directory is missing. Regenerate with `python scripts/gen_bench_index.py`.

The status is a fact about files, not a conclusion about the experiment: it says which documents a
directory holds, never what they found. Read the directory's RESULTS file for the finding.

- `with result`: has a file named `RESULT*`.
- `preregistered, no result`: has a `PREREGISTRATION*` file and no `RESULT*` file.
- `wrapper`: neither, and every file is a script or a README.
- `neither`: neither, and something besides scripts and a README.

"""


def tracked_bench_files() -> list[str] | None:
    """Non-ignored paths under bench/, relative to bench/. None when git cannot list them."""
    try:
        out = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "bench"],
            capture_output=True,
            check=True,
        ).stdout.decode("utf-8")
    except (OSError, subprocess.CalledProcessError):
        return None
    return [p[len("bench/"):] for p in out.split("\0") if p.startswith("bench/")]


def classify(files: list[str]) -> tuple[str, int, int]:
    """(status, prereg count, result count) for the files of one bench directory."""
    names = [f.rsplit("/", 1)[-1] for f in files]
    prereg = sum(1 for n in names if n.startswith("PREREGISTRATION"))
    result = sum(1 for n in names if n.startswith("RESULT"))
    if result:
        return WITH_RESULT, prereg, result
    if prereg:
        return PREREG_ONLY, prereg, result
    only_light = all(n.endswith(_SCRIPT_SUFFIXES) or n.upper().startswith("README") for n in names)
    return (WRAPPER if only_light else NEITHER), prereg, result


def bench_dirs(paths: list[str]) -> dict[str, list[str]]:
    """Directories directly under bench/ with every tracked file below each (relative to it)."""
    by_dir: dict[str, list[str]] = defaultdict(list)
    for p in paths:
        head, sep, rest = p.partition("/")
        if sep:
            by_dir[head].append(rest)
    return dict(by_dir)


def render(paths: list[str]) -> str:
    dirs = bench_dirs(paths)
    rows = []
    counts: dict[str, int] = defaultdict(int)
    for name in sorted(dirs):
        status, prereg, result = classify(dirs[name])
        counts[status] += 1
        rows.append(f"| [`{name}`]({name}/) | {status} | {prereg} | {result} |")
    summary = ", ".join(f"{counts[s]} {s}" for s in (WITH_RESULT, PREREG_ONLY, WRAPPER, NEITHER))
    lines = [
        HEADER.rstrip("\n"),
        "",
        f"{len(dirs)} directories: {summary}.",
        "",
        "| directory | status | PREREGISTRATION files | RESULT files |",
        "|---|---|---:|---:|",
        *rows,
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    paths = tracked_bench_files()
    if paths is None:
        print("git ls-files failed; cannot build the index", file=sys.stderr)
        return 2
    text = render(paths)
    if "--check" in argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("bench/INDEX.md is stale: run python scripts/gen_bench_index.py", file=sys.stderr)
            return 1
        return 0
    INDEX.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
